class Knight:

    def __init__(
            self,
            name: str,
            power: int,
            hp: int,
            armour: list,
            weapon: dict,
            potion: dict | None
    ) -> None:

        self.name = name
        self.power = power
        self.hp = hp
        self.armour = armour
        self.weapon = weapon
        self.potion = potion
        self.battle_power = 0
        self.battle_hp = 0
        self.battle_protection = 0

    def battle_prep(self) -> None:
        self.battle_power = self.power + self.weapon["power"]
        if self.potion:
            self.battle_power += self.potion["effect"].get("power", 0)

        self.battle_hp = self.hp
        if self.potion:
            self.battle_hp += self.potion["effect"].get("hp", 0)

        self.battle_protection = 0

        for armour_part in self.armour:
            self.battle_protection += armour_part["protection"]
        if self.potion:
            self.battle_protection += (
                self.potion["effect"].get("protection", 0)
            )


