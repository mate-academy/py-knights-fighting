def battle(knight_config: dict) -> dict:
    knight_list = {}
    for name, config in knight_config.items():
        knight_list[name] = Knight.create_knight(config)

    fight(knight_list["lancelot"], knight_list["mordred"])
    fight(knight_list["arthur"], knight_list["red_knight"])

    return {knight.name: knight.hp for knight in knight_list.values()}


def fight(knight1: Knight, knight2: Knight) -> None:
    knight1.prepare_to_battle()
    knight2.prepare_to_battle()
    knight1.get_damage(knight2.power)
    knight2.get_damage(knight1.power)
