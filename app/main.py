def clash(unit1: Knight, unit2: Knight) -> None:
    unit1.hp -= unit2.power - unit1.protection
    unit2.hp -= unit1.power - unit2.protection

    if unit1.hp < 0:
        unit1.hp = 0

    if unit2.hp < 0:
        unit2.hp = 0


def battle(knights_config: dict) -> dict:
    knights = []

    for config in knights_config.values():
        knight = Knight(**config)
        knight.ready_up()
        knights.append(knight)

    for i in range(0, len(knights) // 2):
        clash(knights[i], knights[i + 2])

    return {
        knight.name: knight.hp
        for knight in knights
    }


