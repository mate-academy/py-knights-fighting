def battle(knights_config: dict) -> dict:
    participants = preparation(knights_config)
    even_pair = []
    odd_pair = []
    for i in range(0, len(participants), 2):
        even_pair.append(participants[i])

    for i in range(1, len(participants), 2):
        odd_pair.append(participants[i])

    list_pair = [even_pair, odd_pair]
    result_dict = {}

    for fight in list_pair:
        fight[0].hp -= fight[1].power - fight[0].protection
        fight[1].hp -= fight[0].power - fight[1].protection

        if fight[0].hp <= 0:
            fight[0].hp = 0
        if fight[1].hp <= 0:
            fight[1].hp = 0

        for person in fight:
            result_dict[person.name] = person.hp

    return result_dict


