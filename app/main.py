def battle(knights_config: dict) -> dict[str, int]:
    lancelot = Knight(knights_config["lancelot"]).preparations()
    arthur = Knight(knights_config["arthur"]).preparations()
    mordred = Knight(knights_config["mordred"]).preparations()
    red_knight = Knight(knights_config["red_knight"]).preparations()

    first_pair = Battle(lancelot, mordred)
    second_pair = Battle(arthur, red_knight)

    first_pair.main_battle()
    second_pair.main_battle()

    knights = [lancelot, arthur, mordred, red_knight]
    return {knight["name"]: knight["hp"] for knight in knights}
